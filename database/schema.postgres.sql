

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  weight_unit TEXT NOT NULL DEFAULT 'lbs'
);

CREATE TABLE IF NOT EXISTS exercises (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  muscle_group TEXT NOT NULL,
  equipment TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS routines (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  name TEXT NOT NULL,
  description TEXT,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS routine_exercises (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  routine_id INTEGER NOT NULL,
  exercise_id INTEGER NOT NULL,
  target_sets INTEGER NOT NULL,
  target_reps INTEGER NOT NULL,
  exercise_order INTEGER NOT NULL,
  FOREIGN KEY (routine_id) REFERENCES routines(id),
  FOREIGN KEY (exercise_id) REFERENCES exercises(id)
);

CREATE TABLE IF NOT EXISTS workouts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  routine_id INTEGER,
  start_time TEXT NOT NULL,
  end_time TEXT,
  notes TEXT,
  weight_unit TEXT DEFAULT 'lbs' CHECK (weight_unit IS NULL OR weight_unit = 'lbs'),
  FOREIGN KEY (user_id) REFERENCES users(id),
  FOREIGN KEY (routine_id) REFERENCES routines(id)
);

CREATE TABLE IF NOT EXISTS workout_sets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workout_id INTEGER NOT NULL,
  exercise_id INTEGER NOT NULL,
  set_number INTEGER NOT NULL,
  weight DOUBLE PRECISION NOT NULL,
  reps INTEGER NOT NULL,
  completed INTEGER NOT NULL DEFAULT 0,
  FOREIGN KEY (workout_id) REFERENCES workouts(id),
  FOREIGN KEY (exercise_id) REFERENCES exercises(id)
);

CREATE TABLE IF NOT EXISTS body_weight_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL,
  date TEXT NOT NULL,
  weight DOUBLE PRECISION NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS workout_removed_exercises (
  workout_id INTEGER NOT NULL REFERENCES workouts(id) ON DELETE CASCADE,
  exercise_id INTEGER NOT NULL REFERENCES exercises(id),
  PRIMARY KEY (workout_id, exercise_id)
);

CREATE TABLE IF NOT EXISTS profile_pictures (
  user_id INTEGER PRIMARY KEY,
  image TEXT NOT NULL,
  FOREIGN KEY (user_id) REFERENCES users(id)
);




CREATE TABLE IF NOT EXISTS session (sid varchar PRIMARY KEY, sess json NOT NULL, expire timestamp(6) NOT NULL);
CREATE INDEX IF NOT EXISTS session_expire_idx ON session(expire);
